// Embeds the default cast and events text files into a JS module.
import { readFileSync, writeFileSync } from 'node:fs';
const cast = readFileSync(new URL('../data/cast.txt', import.meta.url), 'utf8');
const events = readFileSync(new URL('../data/events.txt', import.meta.url), 'utf8');
const out = `// Generated by tools/gen-defaults.mjs from data/cast.txt and data/events.txt. Do not edit.\n` +
  `export const DEFAULT_CAST_TEXT = ${JSON.stringify(cast)};\n` +
  `export const DEFAULT_EVENTS_TEXT = ${JSON.stringify(events)};\n`;
writeFileSync(new URL('../src/data/defaultData.js', import.meta.url), out);
console.log('defaultData.js written', out.length, 'bytes');
